// @ts-check
// Generates the web app's code from the HTTP contract, ../api/openapi.yaml:
//
//   src/api/schema.d.ts          the openapi-typescript types, for openapi-fetch;
//   src/mocks/operations.gen.ts  every operation's method, path, success status and media type,
//                                for the MSW handlers that serve ../api/examples.
//
// `node scripts/gen-api.mjs` writes both files; `--check` writes nothing and fails when either
// is stale (part of `npm run reviewable`). The operation table follows api/operations.go: the
// path is the effective server's path followed by the spec path, and the success response is
// the lowest 2xx with a body, else the lowest 2xx, else the lowest 3xx.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import openapiTS, { COMMENT_HEADER, astToString } from 'openapi-typescript';

const spec = new URL('../../api/openapi.yaml', import.meta.url);
const schemaFile = new URL('../src/api/schema.d.ts', import.meta.url);
const operationsFile = new URL(
  '../src/mocks/operations.gen.ts',
  import.meta.url,
);

// The methods MSW can mock (http.*); the spec uses no others (trace fails the generator).
const METHODS = ['delete', 'get', 'head', 'options', 'patch', 'post', 'put'];

/**
 * @typedef {{ id: string, method: string, path: string, status: number, contentType: string }} Operation
 */

/** @param {any} doc @param {any} value */
function deref(doc, value) {
  let v = value;
  while (v && typeof v.$ref === 'string') {
    if (!v.$ref.startsWith('#/')) throw new Error(`unsupported $ref ${v.$ref}`);
    v = v.$ref
      .slice(2)
      .split('/')
      .reduce((/** @type {any} */ o, /** @type {string} */ k) => o?.[k], doc);
    if (v === undefined) throw new Error(`unresolved $ref ${value.$ref}`);
  }
  return v;
}

/** @param {any[] | undefined} servers */
function serverPath(servers) {
  if (!servers || servers.length === 0) return '';
  const url = new URL(servers[0].url, 'http://placeholder');
  return url.pathname.replace(/\/$/, '');
}

/** @param {any} doc @param {any} responses @returns {{ status: number, contentType: string }} */
function success(doc, responses) {
  const codes = Object.keys(responses ?? {})
    .map(Number)
    .filter(Number.isInteger)
    .sort((a, b) => a - b);
  let candidates = codes.filter((c) => c >= 200 && c <= 299);
  if (candidates.length === 0)
    candidates = codes.filter((c) => c >= 300 && c <= 399);
  if (candidates.length === 0) throw new Error('no 2xx or 3xx response');
  for (const code of candidates) {
    const content = deref(doc, responses[String(code)])?.content;
    const types = Object.keys(content ?? {});
    if (types.length === 0) continue;
    if (types.length !== 1)
      throw new Error(
        `response ${code} has ${types.length} media types, want 1`,
      );
    return { status: code, contentType: types[0] };
  }
  return { status: candidates[0], contentType: '' };
}

/** @param {any} doc @returns {Operation[]} */
function operations(doc) {
  /** @type {Operation[]} */
  const out = [];
  for (const p of Object.keys(doc.paths ?? {}).sort()) {
    const item = doc.paths[p];
    if (item.trace) throw new Error(`trace ${p}: MSW can't mock TRACE`);
    for (const method of METHODS.filter((m) => item[m])) {
      const op = item[method];
      const servers = op.servers?.length
        ? op.servers
        : item.servers?.length
          ? item.servers
          : doc.servers;
      try {
        out.push({
          id: op.operationId,
          method,
          path: serverPath(servers) + p,
          ...success(doc, op.responses),
        });
      } catch (err) {
        throw new Error(
          `${method} ${p}: ${/** @type {Error} */ (err).message}`,
          { cause: err },
        );
      }
    }
  }
  return out;
}

/** @param {Operation[]} ops */
function renderOperations(ops) {
  const rows = ops.map(
    (o) =>
      `  {\n    id: '${o.id}',\n    method: '${o.method}',\n    path: '${o.path}',\n    status: ${o.status},\n    contentType: '${o.contentType}',\n  },`,
  );
  return `// Code generated by \`npm run gen:api\` from ../api/openapi.yaml. DO NOT EDIT.

import type { operations as Operations } from '@/api/schema';

export interface MockOperation {
  id: keyof Operations;
  method: 'delete' | 'get' | 'head' | 'options' | 'patch' | 'post' | 'put';
  /** The full path template, e.g. /api/v1/tasks/{id}. */
  path: string;
  /** The success status: the lowest 2xx with a body, else the lowest 2xx, else the lowest 3xx. */
  status: number;
  /** The success response's media type; empty when it has no body. */
  contentType: string;
}

export const operations: readonly MockOperation[] = [
${rows.join('\n')}
];
`;
}

async function main() {
  const check = process.argv.includes('--check');
  const doc = yaml.load(await readFile(spec, 'utf8'));
  const want = new Map([
    [schemaFile, COMMENT_HEADER + astToString(await openapiTS(spec))],
    [operationsFile, renderOperations(operations(doc))],
  ]);
  const stale = [];
  for (const [file, content] of want) {
    if (check) {
      const have = await readFile(file, 'utf8').catch(() => '');
      if (have !== content) stale.push(fileURLToPath(file));
    } else {
      await writeFile(file, content);
    }
  }
  if (stale.length > 0) {
    console.error(
      `generated files are stale: run npm run gen:api and commit\n  ${stale.join('\n  ')}`,
    );
    process.exit(1);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
